const UNSAFE_METHODS = new Set(['POST', 'PUT', 'PATCH', 'DELETE']);

function endpoint(method, path, permission, response = 'json') {
  return Object.freeze({
    method,
    path,
    permission,
    authenticated: true,
    activeUser: true,
    csrf: UNSAFE_METHODS.has(method),
    response,
  });
}

